    fig.patch.set_facecolor("#0b0f19")

    title_font = {"fontsize": 13, "fontweight": "bold", "color": "#f1f5f9"}
    label_font = {"fontsize": 10, "color": "#94a3b8"}

    for ax in axes.flat:
        ax.set_facecolor("#111827")
        ax.tick_params(colors="#94a3b8")
        for spine in ax.spines.values():
            spine.set_color("#374151")

    models = ["1. Naive Base\n(No Dual-Loop)", "2. HADL Before\nLearning", "3. HADL After\nLearning (Teaching)"]
    m_naive = summary["metrics_naive"]
