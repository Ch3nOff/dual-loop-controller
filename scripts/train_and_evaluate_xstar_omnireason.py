# Text for General Perplexity Check
PERPLEXITY_TEXT = """
Artificial intelligence (AI) is intelligence demonstrated by machines, as opposed to the intelligence of living beings, primarily of humans.
It is a field of study in computer science that develops and studies intelligent machines. Such machines may be called AIs.
AI technology is widely used throughout industry, government, and science. Some high-profile applications are advanced web search engines,
recommendation systems, understanding human speech, autonomous vehicles, generative or creative tools, and superhuman play in games.
"""

def compute_perplexity(model, tokenizer, text: str) -> float:
    enc = tokenizer(text, return_tensors="pt").to(DEVICE)
    with torch.no_grad():
        out = model(enc.input_ids, labels=enc.input_ids)
        loss = out.loss
    return round(float(math.exp(loss.item())), 3)

def evaluate_100_questions(model, tokenizer, desc: str = "Model") -> Dict[str, Any]:
    print(f"\n[*] Evaluating {desc} across 20 Benchmarks (100 Questions Total)...", flush=True)
    bench_results = {}
    total_correct = 0
    speeds = []

    # Initialize benchmark buckets
    for item in BENCHMARK_SUITE_100Q:
        b_name = item["benchmark"]
        if b_name not in bench_results:
            bench_results[b_name] = {
                "pillar": item["pillar"],
                "total": 0,
                "correct": 0,
                "score_pct": 0.0,
                "questions": []
            }

    t_start = time.perf_counter()
    for idx, item in enumerate(BENCHMARK_SUITE_100Q):
        b_name = item["benchmark"]
        messages = [{"role": "user", "content": item["prompt"]}]
        inp_str = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inp = tokenizer(inp_str, return_tensors="pt").to(DEVICE)

        t0 = time.perf_counter()
        with torch.no_grad():
            out_ids = model.generate(
                inp.input_ids,
                max_new_tokens=180,
                do_sample=False,
                pad_token_id=tokenizer.eos_token_id
            )
        dt = time.perf_counter() - t0
        gen_tokens = out_ids[0][inp.input_ids.shape[1]:]
        tok_speed = len(gen_tokens) / max(dt, 1e-4)
        speeds.append(tok_speed)

        resp = tokenizer.decode(gen_tokens, skip_special_tokens=True).strip()
        passed = item["check"](resp)

        if passed:
            total_correct += 1
            bench_results[b_name]["correct"] += 1

        bench_results[b_name]["total"] += 1
        bench_results[b_name]["questions"].append({
            "id": item["id"],
            "passed": passed,
            "target": item["target"],
            "snippet": resp[:90]
        })

        if (idx + 1) % 20 == 0 or (idx + 1) == len(BENCHMARK_SUITE_100Q):
            elapsed_tot = time.perf_counter() - t_start
            print(f"  [{idx+1:03d}/100] Progress: {total_correct}/{idx+1} correct ({total_correct/(idx+1)*100:.1f}%) | Speed: {np.mean(speeds):.1f} tok/s | Elapsed: {elapsed_tot:.1f}s", flush=True)

    # Compute per-benchmark percentage
    for b_name, b_data in bench_results.items():
        b_data["score_pct"] = round((b_data["correct"] / max(1, b_data["total"])) * 100.0, 1)

    overall_pct = round((total_correct / len(BENCHMARK_SUITE_100Q)) * 100.0, 1)
    avg_speed = round(float(np.mean(speeds)), 1)
    return {
        "overall_score_pct": overall_pct,
        "total_correct": total_correct,
        "total_questions": len(BENCHMARK_SUITE_100Q),
        "avg_speed_tok_s": avg_speed,
        "benchmarks": bench_results
    }

