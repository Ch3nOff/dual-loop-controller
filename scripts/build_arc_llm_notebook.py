class CognitiveWorkingMemory(nn.Module):
    """Compresses prompt representations [B, N, D] into compact working memory slots [B, M, D]."""
    def __init__(self, d_model: int, num_slots: int = 16, n_heads: int = 4):
        super().__init__()
